/** Renders a document definition to PDF bytes (pdfmake + bundled Roboto font, loaded lazily). */
export async function renderPdf(doc: TDocumentDefinitions): Promise<Uint8Array> {
  const [{ default: pdfMake }, { default: vfs }] = await Promise.all([import('pdfmake/build/pdfmake'), import('pdfmake/build/vfs_fonts')])
  pdfMake.addVirtualFileSystem(vfs)
  const buffer = await pdfMake.createPdf(doc).getBuffer()
  return new Uint8Array(buffer)
}

/** Loads pdfmake and its fonts ahead of time so downloads also work offline later. */
export async function preloadPdf(): Promise<void> {
  await Promise.all([import('pdfmake/build/pdfmake'), import('pdfmake/build/vfs_fonts')])
}
