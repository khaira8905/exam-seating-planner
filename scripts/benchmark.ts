/**
 * Benchmark: times the full pipeline for 300 / 1,200 / 5,000 students under
 * every rule, with both methods, and re-checks each plan with the independent
 * checker (clashes must be 0). Runs in Node — the same code the browser runs
 * in its Web Worker.
 *
 *   npm run bench            → prints a Markdown table, writes docs/benchmark.{md,json}
 *   npm run bench -- --quick → one run per case, strict rule only
 */
import fs from 'node:fs'
import os from 'node:os'
import highsLoader from 'highs'
import { checkPlan } from '../src/lib/engine/checker'
import type { HighsLike } from '../src/lib/engine/milp'
import { solve } from '../src/lib/engine/solve'
import { generateSample } from '../src/lib/sample/generate'
import { seatLabel } from '../src/lib/seatLabel'
import type { Method, Plan, Strictness } from '../src/lib/types'

const quick = process.argv.includes('--quick')
const RUNS = quick ? 1 : 3
const SIZES = [
  { students: 300, rooms: 10 as number | undefined },
  { students: 1200, rooms: 30 as number | undefined },
  { students: 5000, rooms: undefined },
]
const RULES: Strictness[] = quick ? ['strict'] : ['basic', 'strict', 'very-strict', 'bench']
const METHODS: Method[] = ['pattern', 'optimised']

interface Row {
  students: number
  roomsAvailable: number
  rule: Strictness
  method: Method
  medianMs: number
  minMs: number
  maxMs: number
  roomsUsed: number
  emptySeats: number
  clashes: number
  checkedPairs: number
  specialFrontPct: number
  specialGroundPct: number
  rowSpread: number
  roomsOptimised: number
}

/** Share of special-needs students in the front two rows / on the ground floor. */
function quality(plan: Plan) {
  const byRoll = new Map(plan.students.map((s) => [s.roll, s]))
  const rooms = new Map(plan.rooms.map((r) => [r.id, r]))
  const special = plan.seats.filter((a) => byRoll.get(a.roll)?.specialNeeds)
  const front = special.filter((a) => a.row <= 1).length
  const ground = special.filter((a) => rooms.get(a.roomId)?.floor === 0).length
  // Row spread: per room, (max − min) empty seats per row, averaged over rooms that have empty seats.
  const spreads: number[] = []
  for (const id of plan.roomOrder) {
    const room = rooms.get(id)!
    const blocked = new Set(room.blocked)
    const perRow = Array.from({ length: room.rows }, (_, r) => {
      let usable = 0
      for (let c = 0; c < room.cols; c++) if (!blocked.has(seatLabel(r, c))) usable++
      return usable - plan.seats.filter((a) => a.roomId === id && a.row === r).length
    })
    if (perRow.some((e) => e > 0)) spreads.push(Math.max(...perRow) - Math.min(...perRow))
  }
  return {
    specialFrontPct: special.length ? Math.round((front / special.length) * 100) : 100,
    specialGroundPct: special.length ? Math.round((ground / special.length) * 100) : 100,
    rowSpread: spreads.length ? spreads.reduce((a, b) => a + b, 0) / spreads.length : 0,
  }
}

const median = (xs: number[]) => [...xs].sort((a, b) => a - b)[Math.floor(xs.length / 2)]

async function main() {
  const highs = (await highsLoader()) as unknown as HighsLike
  const rows: Row[] = []
  for (const size of SIZES) {
    const { students, rooms } = generateSample({ students: size.students, rooms: size.rooms })
    for (const rule of RULES) {
      for (const method of METHODS) {
        const times: number[] = []
        let last: Plan | null = null
        for (let i = 0; i < RUNS; i++) {
          const t0 = performance.now()
          const out = await solve({ students, rooms, rule, method, session: { date: '2026-11-24', slot: 'morning' } }, { highs })
          times.push(performance.now() - t0)
          if (!out.ok) throw new Error(`${size.students}/${rule}/${method}: ${out.problem.title}`)
          last = out.plan
        }
        const plan = last!
        const check = checkPlan(plan)
        const row: Row = {
          students: size.students,
          roomsAvailable: rooms.length,
          rule,
          method,
          medianMs: Math.round(median(times)),
          minMs: Math.round(Math.min(...times)),
          maxMs: Math.round(Math.max(...times)),
          roomsUsed: plan.stats.roomsUsed,
          emptySeats: plan.stats.emptySeats,
          clashes: check.clashes.length + check.problems.length,
          checkedPairs: check.checkedPairs,
          roomsOptimised: plan.stats.roomsByMethod.optimised,
          ...quality(plan),
        }
        rows.push(row)
        console.error(`${row.students} ${row.rule} ${row.method}: ${row.medianMs} ms, clashes ${row.clashes}`)
      }
    }
  }

  const cpu = os.cpus()[0]?.model ?? 'unknown CPU'
  const env = `Node ${process.version} · ${cpu} (${os.cpus().length} threads) · ${RUNS} run(s) per case, median shown`
  const md = [
    `<!-- generated by \`npm run bench\` on ${new Date().toISOString().slice(0, 10)} -->`,
    `_${env}_`,
    '',
    '| Students | Rooms used / available | Rule | Method | Time (median) | Clashes | Special needs in front 2 rows | Avg. row spread of empty seats |',
    '|---:|---:|---|---|---:|---:|---:|---:|',
    ...rows.map(
      (r) =>
        `| ${r.students.toLocaleString('en-IN')} | ${r.roomsUsed} / ${r.roomsAvailable} | ${r.rule} | ${r.method === 'optimised' ? `HiGHS (${r.roomsOptimised} rooms)` : 'pattern'} | ${
          r.medianMs >= 1000 ? `${(r.medianMs / 1000).toFixed(2)} s` : `${r.medianMs} ms`
        } | ${r.clashes} | ${r.specialFrontPct}% | ${r.rowSpread.toFixed(2)} |`,
    ),
  ].join('\n')
  console.log(md)
  if (!quick) {
    fs.mkdirSync('docs', { recursive: true })
    fs.writeFileSync('docs/benchmark.md', md + '\n')
    fs.writeFileSync('docs/benchmark.json', JSON.stringify({ env, rows }, null, 2) + '\n')
  }
  if (rows.some((r) => r.clashes > 0)) {
    console.error('FAIL: a plan had clashes')
    process.exit(1)
  }
}

void main()
